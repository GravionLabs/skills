function Open-Url([string]$Url) {
    Write-Host ("  " + (Paint '32' '↗ opening') + " $Url")
    try {
        if ($IsWindows) { Start-Process $Url }
        elseif ($IsMacOS) { & open $Url 2>&1 | Out-Null }
        else { & xdg-open $Url 2>&1 | Out-Null }
        if ($LASTEXITCODE -gt 0) { throw 'no opener' }
    } catch {
        Write-Warn "couldn't open a browser, so visit it manually: $Url"
    }
}

function Suspend-Wizard([string]$Message = 'Press Enter to continue') {
    Write-Host (Paint '2' "  $Message ") -NoNewline
    $null = Read-Host
}

function Confirm-Wizard([string]$Question) {
    Write-Host (Paint '33' "  ? $Question [y/N] ") -NoNewline
    (Read-Host) -match '^[Yy]'
}

# Current value of a key in the env file, with the single quotes of Set-EnvValue undone.
function Get-ExistingValue([string]$Key) {
    if (-not (Test-Path -LiteralPath $EnvFile)) { return $null }
    $line = Get-Content -LiteralPath $EnvFile | Where-Object { $_ -like "$Key=*" } | Select-Object -Last 1
    if (-not $line) { return $null }
    $value = $line.Substring($Key.Length + 1)
    if ($value.Length -ge 2 -and $value.StartsWith("'") -and $value.EndsWith("'")) {
        return $value.Substring(1, $value.Length - 2).Replace("'\''", "'")
    }
    if ($value.Length -ge 2 -and $value.StartsWith('"') -and $value.EndsWith('"')) {
        $inner = $value.Substring(1, $value.Length - 2)
        if ($inner -match '[\\$"]') { return $null }
        return $inner
    }
    $value
}

# Reads a value into $script:Values[$Key]; Enter keeps the existing value of the env file.
function Read-Value([string]$Key, [string]$Prompt) {
    $current = Get-ExistingValue $Key
    $suffix = if ($current) { Paint '2' ' [Enter keeps current]' } else { '' }
    $entered = Read-Host -Prompt ("  $Prompt$suffix")
    if (-not $entered -and $current) { $entered = $current }
    $script:Values[$Key] = $entered
    $entered
}

# Like Read-Value, but the input is hidden and never echoed.
function Read-SecretValue([string]$Key, [string]$Prompt) {
    $current = Get-ExistingValue $Key
    $suffix = if ($current) { Paint '2' ' [Enter keeps current]' } else { '' }
    $secure = Read-Host -Prompt ("  $Prompt$suffix") -AsSecureString
    $entered = [System.Net.NetworkCredential]::new('', $secure).Password
    if (-not $entered -and $current) { $entered = $current }
    $script:Values[$Key] = $entered
    $entered
}

# Upserts KEY='VALUE' into the env file (replaces any existing line). Idempotent.
function Set-EnvValue([string]$Key, [string]$Value) {
    if (-not (Test-Path -LiteralPath $EnvFile)) {
        $null = New-Item -ItemType File -Path $EnvFile
        if (-not $IsWindows) { & chmod 600 $EnvFile }
    }
    $lines = @(Get-Content -LiteralPath $EnvFile | Where-Object { $_ -notlike "$Key=*" })
    $lines += "$Key='" + $Value.Replace("'", "'\''") + "'"
    Set-Content -LiteralPath $EnvFile -Value $lines
    $script:Values[$Key] = $Value
    $script:WrittenEnv.Add($Key)
    Write-Host ("  " + (Paint '32' '✓ wrote') + " $Key → $EnvFile")
}

function Test-GhReady {
    if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { return $false }
    & gh auth status 2>&1 | Out-Null
    $LASTEXITCODE -eq 0
}

# Sets a GitHub Actions repo secret via gh; the value goes through stdin, never the command line.
function Set-GhSecret([string]$Name, [string]$Value) {
    if (Test-GhReady) {
        $Value | & gh secret set $Name 2>&1 | Out-Null
        if ($LASTEXITCODE -eq 0) {
            $script:WrittenSecret.Add($Name)
            Write-Host ("  " + (Paint '32' '✓ set') + " GitHub secret $Name")
            return
        }
    }
    $script:Skipped.Add("GitHub secret $Name (set it manually: gh secret set $Name)")
    Write-Warn "skipped GitHub secret $Name`: gh not ready; set it later"
}

# Sets a GitHub Actions repo variable (non-secret).
function Set-GhVariable([string]$Name, [string]$Value) {
    if (Test-GhReady) {
        & gh variable set $Name --body $Value 2>&1 | Out-Null
        if ($LASTEXITCODE -eq 0) {
            Write-Host ("  " + (Paint '32' '✓ set') + " GitHub variable $Name")
            return
        }
    }
    $script:Skipped.Add("GitHub variable $Name")
    Write-Warn "skipped GitHub variable $Name, gh not ready; set it later"
}

function Complete-Wizard {
    Clear-Wizard
    Write-Host ''
    Write-Host ('  ' + (Paint '1;32' '✓ Setup complete'))
    if ($script:WrittenEnv.Count) { Write-Note "wrote $($script:WrittenEnv.Count) value(s) to ${EnvFile}: $($script:WrittenEnv -join ' ')" }
    if ($script:WrittenSecret.Count) { Write-Note "set $($script:WrittenSecret.Count) GitHub secret(s): $($script:WrittenSecret -join ' ')" }
    if ($script:Skipped.Count) {
        Write-Host ''
        Write-Warn 'still to do by hand:'
        foreach ($s in $script:Skipped) { Write-Note "  - $s" }
    }
    Write-Host ''
}

