function Show-Banner([string]$Title) {
    Clear-Wizard
    Write-Host ''
    Write-Host ('  ' + (Paint '1;34' $Title))
    Write-Host (Paint '2' "  $($script:TotalStages) stages")
    Write-Host ''
    Write-Host (Paint '2' '  You drive the browser; this wizard tells you exactly what to do and')
    Write-Host (Paint '2' '  captures the values you copy back. Stop any time with Ctrl-C and re-run')
    Write-Host (Paint '2' '  later, since it remembers values already saved.')
    Suspend-Wizard 'Ready to start?'
}

function Start-Stage([string]$Name) {
