}

function Write-Say([string]$Text) { Write-Host "  $Text" }
function Write-Step([string]$Text) { Write-Host ("  " + (Paint '34' '•') + " $Text") }
function Write-Note([string]$Text) { Write-Host (Paint '2' "  $Text") }
