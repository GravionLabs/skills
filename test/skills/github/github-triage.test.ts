import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { PwshWorker } from '../../helpers/pwsh-worker';
import { expectSkillHelp } from '../../helpers/skill-help';

const skillDir = path.resolve(__dirname, '../../../skills/github/github-triage');
const script = path.join(skillDir, 'scripts/Get-TriageQueue.ps1');
const read = (p: string) => fs.readFileSync(path.join(skillDir, p), 'utf8');

describe('github-triage skill', () => {
  it('has valid frontmatter and stays within 100 lines', () => {
    const text = read('SKILL.md');
    expect(text.split('\n').length).toBeLessThanOrEqual(101);
    const fm = text.match(
      /^---\nname: github-triage\ndescription: '(.+)'\ndisable-model-invocation: true\nmetadata:\n  opencode\/autoinvoke: 'false'\n---\n/,
    );
    expect(fm).not.toBeNull();
    expect(fm?.[1]?.length ?? 0).toBeLessThanOrEqual(1024);
  });

  it('follows the help convention', () => {
    expectSkillHelp(skillDir);
  });

  it('states the approval gate, the AI marker and the outcomes', () => {
    const all = read('SKILL.md') + read('references/triage.md');
    expect(all).toContain('> *This was generated by AI during triage.*');
    expect(all).toMatch(/without the owner's approval/);
    for (const term of [
      'needs-info',
      'Triage notes',
      '.out-of-scope/',
      'github-milestone assign',
      'diagnose',
      'already implemented',
    ]) {
      expect(all).toContain(term);
    }
  });

  describe('Get-TriageQueue.ps1', () => {
    let worker: PwshWorker;
    let tmp: string;
    beforeAll(() => {
      worker = new PwshWorker(script);
      tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'triage-'));
    });
    afterAll(async () => {
      worker.close();
      fs.rmSync(tmp, { recursive: true, force: true });
    });

    it('creates exactly the labels needs-triage and needs-info when missing', async () => {
      const r = await worker.run(['-Mode', 'labels', '-DryRun', '-Existing', 'bug'], { cwd: tmp });
      expect(r.status).toBe(0);
      expect(JSON.parse(r.stdout)).toEqual([
        { label: 'needs-triage', state: 'created' },
        { label: 'needs-info', state: 'created' },
      ]);
      const again = await worker.run(
        ['-Mode', 'labels', '-DryRun', '-Existing', 'needs-info,needs-triage'],
        { cwd: tmp },
      );
      expect(JSON.parse(again.stdout).map((l: { state: string }) => l.state)).toEqual([
        'exists',
        'exists',
      ]);
    });

    it('lists the three groups oldest first', async () => {
      const u = (login: string) => ({ login });
      const issue = (n: number, d: string, labels: string[], comments: unknown[] = []) => ({
        number: n,
        title: `t${n}`,
        createdAt: d,
        author: u('rep'),
        labels: labels.map((name) => ({ name })),
        comments,
      });
      const issues = [
        issue(5, '2026-03-01T00:00:00Z', []),
        issue(2, '2026-01-01T00:00:00Z', []),
        issue(3, '2026-02-01T00:00:00Z', ['pbi']),
        issue(4, '2026-02-02T00:00:00Z', ['needs-triage']),
        issue(
          6,
          '2026-02-03T00:00:00Z',
          ['needs-info'],
          [
            { author: u('owner'), body: '## Triage notes', createdAt: 'a' },
            { author: u('rep'), body: 'here is more', createdAt: 'b' },
          ],
        ),
        issue(
          7,
          '2026-02-04T00:00:00Z',
          ['needs-info'],
          [{ author: u('owner'), body: '## Triage notes', createdAt: 'a' }],
        ),
        issue(
          8,
          '2026-02-05T00:00:00Z',
          ['needs-info'],
          [
            { author: u('rep'), body: 'early', createdAt: 'a' },
            { author: u('owner'), body: '## Triage notes', createdAt: 'b' },
          ],
        ),
      ];
      const file = path.join(tmp, 'issues.json');
      fs.writeFileSync(file, JSON.stringify(issues));
      const r = await worker.run(['-Mode', 'list', '-IssuesFile', file], { cwd: tmp });
      expect(r.status).toBe(0);
      const q = JSON.parse(r.stdout);
      const nums = (g: { number: number }[]) => g.map((i) => i.number);
      expect(nums(q.noLevel)).toEqual([2, 5]);
      expect(nums(q.needsTriage)).toEqual([4]);
      expect(nums(q.needsInfoReplied)).toEqual([6]);
    });
  });
});
