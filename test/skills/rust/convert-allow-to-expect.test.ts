import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

import { PwshWorker } from '../../helpers/pwsh-worker';

const SCRIPT = path.resolve(
  __dirname,
  '../../../skills/rust/rust-implementation/scripts/Convert-AllowToExpect.ps1',
);
const DEFAULT = 'legacy suppression, migrated from allow';

describe('Convert-AllowToExpect.ps1', () => {
  let worker: PwshWorker;
  let tmp: string;
  let repo: string;
  let stubBin: string;
  const read = (rel: string) => fs.readFileSync(path.join(repo, rel), 'utf8');
  const write = (rel: string, text: string) => {
    const p = path.join(repo, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, text);
  };
  const files: Record<string, string> = {
    'src/single.rs': '#[allow(dead_code)]\nfn a() {}\n',
    'src/multi.rs': '#[allow(clippy::too_many_lines, dead_code,)]\nfn a() {}\n',
    'src/reason.rs': '#[allow(dead_code, reason = "kept")]\nfn a() {}\n',
    'src/comment.rs': '// used by the macro "x"\n#[allow(dead_code)]\nfn a() {}\n',
    'src/inner.rs': '#![allow(missing_docs)]\nfn a() {}\n',
    'src/gen.rs': '// @generated by prost\n#[allow(dead_code)]\nfn a() {}\n',
    'target/debug/build.rs': '#[allow(dead_code)]\nfn a() {}\n',
  };

  beforeAll(() => {
    worker = new PwshWorker(SCRIPT);
    tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'allow-expect-'));
    stubBin = path.join(tmp, 'bin');
    fs.mkdirSync(stubBin);
    const stub = path.join(stubBin, 'cargo');
    fs.writeFileSync(
      stub,
      '#!/bin/sh\necho "warning: this lint expectation is unfulfilled"\necho "  --> src/single.rs:1:10"\necho "   = note: `#[warn(unfulfilled_lint_expectations)]` on by default"\n',
    );
    fs.chmodSync(stub, 0o755);
  });
  afterAll(async () => {
    worker.close();
    fs.rmSync(tmp, { recursive: true, force: true });
  });
  beforeEach(() => {
    repo = fs.mkdtempSync(path.join(tmp, 'repo-'));
    for (const [k, v] of Object.entries(files)) write(k, v);
    write('Cargo.toml', '[package]\nname = "x"\n');
  });

  const run = (...args: string[]) =>
    worker.run(['-Path', repo, ...args], {
      cwd: repo,
      env: { ...process.env, PATH: `${stubBin}${path.delimiter}${process.env.PATH}` },
    });

  it('converts allow to expect with reasons and skips generated files and target/', async () => {
    const r = await run();
    expect(r.status).toBe(0);
    expect(read('src/single.rs')).toContain(`#[expect(dead_code, reason = "${DEFAULT}")]`);
    expect(read('src/multi.rs')).toContain(
      `#[expect(clippy::too_many_lines, dead_code, reason = "${DEFAULT}")]`,
    );
    expect(read('src/reason.rs')).toContain('#[expect(dead_code, reason = "kept")]');
    expect(read('src/comment.rs')).toContain(
      '#[expect(dead_code, reason = "used by the macro \\"x\\"")]',
    );
    expect(read('src/inner.rs')).toContain(`#![expect(missing_docs, reason = "${DEFAULT}")]`);
    expect(read('src/gen.rs')).toBe(files['src/gen.rs']);
    expect(read('target/debug/build.rs')).toBe(files['target/debug/build.rs']);
    expect(read('Cargo.toml')).toBe('[package]\nname = "x"\n');
    expect(r.stdout).toContain('converted: 5 attributes in 5 files');
  });

  it('lists unfulfilled expectations from the clippy run', async () => {
    const r = await run();
    expect(r.stdout).toContain('unfulfilled_lint_expectations: src/single.rs:1:10');
    expect(r.stdout).toContain('unfulfilled expectations: 1');
  });

  it('-WhatIf lists the changes and changes nothing', async () => {
    const r = await run('-WhatIf');
    expect(r.status).toBe(0);
    expect(r.stdout).toContain('src/single.rs:1: #[allow(dead_code)] -> #[expect(dead_code');
    expect(r.stdout).toContain('whatif: 5 attributes in 5 files would change');
    expect(r.stdout).not.toContain('unfulfilled');
    for (const [k, v] of Object.entries(files)) expect(read(k)).toBe(v);
  });

  it('fails for a missing path', async () => {
    const r = await worker.run(['-Path', path.join(tmp, 'nope')], { cwd: tmp });
    expect(r.status).not.toBe(0);
    expect(r.stderr + r.stdout).toContain('Path not found');
  });
});
